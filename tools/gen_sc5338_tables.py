#!/usr/bin/env python3
"""
Generate src/kernel-patches/sc5338-tables.h from the SC5338 reference header.

The reference file (sc5338-regs-rockchip.h) is a *documentation/analysis*
artifact that contains 5 register arrays (3 of which the S4602 driver does
not use). Including it directly into the kernel would produce unused-static
warnings (and potentially -Werror failures).

This script extracts ONLY the two arrays the sc5338.c driver actually
registers, producing a clean, byte-exact build header:

  - sc5338_public_linear_2880x1620_30fps_2lane_regs  (linear 2880x1620 30fps 2-lane)
  - sc5338_vendor_mode3_regs                          (HDR_X2 2880x1620 15fps 2-lane,
                                                       device-exact, S4602 dmesg hdr:5)

`struct regval` is intentionally NOT defined here — the includer (sc5338.c)
defines it.  SC5338_REG_NULL (0x0000) matches sc5338.c's local REG_NULL.

Usage:  python3 tools/gen_sc5338_tables.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "src", "kernel-patches", "sc5338-regs-rockchip.h")
OUT = os.path.join(HERE, "..", "src", "kernel-patches", "sc5338-tables.h")

# Order matters: linear first, then HDR_X2 (matches supported_modes[] in sc5338.c).
TARGETS = [
    "sc5338_public_linear_2880x1620_30fps_2lane_regs",
    "sc5338_vendor_mode3_regs",
]


def extract_array(src_lines, name):
    """Return the source lines for `static const struct regval NAME[] = { ... };`."""
    start_marker = "static const struct regval %s[] = {" % name
    start = None
    for i, line in enumerate(src_lines):
        if start_marker in line:
            start = i
            break
    if start is None:
        raise SystemExit("ERROR: array '%s' not found in reference header" % name)

    out = [src_lines[start].rstrip("\n")]
    for line in src_lines[start + 1:]:
        out.append(line.rstrip("\n"))
        if line.strip() == "};":
            return out
    raise SystemExit("ERROR: array '%s' not terminated with '};'" % name)


def main():
    with open(SRC, "r", encoding="utf-8") as f:
        src_lines = f.readlines()

    blocks = []
    for name in TARGETS:
        blocks.append("\n".join(extract_array(src_lines, name)))

    header = (
        "/* SC5338 register tables - build artifact for the S4602 (RV1109) kernel driver.\n"
        " *\n"
        " * Generated by tools/gen_sc5338_tables.py from sc5338-regs-rockchip.h (the\n"
        " * full reference/analysis file, which is NOT compiled). This header contains\n"
        " * ONLY the two modes sc5338.c actually registers:\n"
        " *   - sc5338_public_linear_2880x1620_30fps_2lane_regs : linear 2880x1620 30fps 2-lane\n"
        " *   - sc5338_vendor_mode3_regs                        : HDR_X2 2880x1620 15fps 2-lane\n"
        " *                                                     (device-exact, S4602 dmesg hdr:5)\n"
        " *\n"
        " * struct regval { u16 addr; u8 val; }; is defined by the includer (sc5338.c).\n"
        " * SC5338_REG_NULL (0x0000) matches sc5338.c's local REG_NULL terminator.\n"
        " * Source: SmartSens SC5338 (chip id 0xce50), 2-lane MIPI CSI-2.\n"
        " */\n"
        "#ifndef _SC5338_TABLES_H_\n"
        "#define _SC5338_TABLES_H_\n"
        "\n"
        "#define SC5338_REG_NULL 0x0000\n"
        "\n"
        + "\n\n".join(blocks)
        + "\n\n#endif /* _SC5338_TABLES_H_ */\n"
    )

    with open(OUT, "w", encoding="utf-8") as f:
        f.write(header)

    print("Wrote %s (%d bytes)" % (os.path.relpath(OUT), len(header)))


if __name__ == "__main__":
    main()
